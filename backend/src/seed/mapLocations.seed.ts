// ─── Types ────────────────────────────────────────────────────────────────────
interface LocationSeed {
  locationId: string;
  name: string;
  category: LocationCategory;
  latitude: number;
  longitude: number;
  mapX: number;
  mapY: number;
  pollutionMultiplier: number;
  sensorAvailable: boolean;
  /**
   * Optional explicit override. When omitted, sensorType is derived
   * deterministically from `category` + `sensorAvailable` by
   * deriveSensorType() below — see that function for the mapping rule.
   */
  sensorType?: SensorType;
  description: string;
}

interface WaterBodySeed {
  id: string;
  name: string;
  /** Legacy SVG canvas position (0–100%). Retained for the drawer list. */
  x: number;
  y: number;
  /** Real-world coordinates (Phase 1 GIS upgrade) — required for map rendering. */
  latitude: number;
  longitude: number;
}

interface ZonesSeed {
  residential: number;
  industrial: number;
  commercial: number;
  greenCover: number;
}

interface CitySeed {
  cityId: string;
  center: { lat: number; lng: number };
  zoom: number;
  /** Optional camera bearing in degrees. Defaults to 0 (north-up) when omitted. */
  bearing?: number;
  /** Optional camera pitch/tilt in degrees. Defaults to 0 (top-down) when omitted. */
  pitch?: number;
  waterBodies: WaterBodySeed[];
  zones: ZonesSeed;
  locations: LocationSeed[];
}

