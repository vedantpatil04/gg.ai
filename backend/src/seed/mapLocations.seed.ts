// ─── Sensor-type derivation (Phase 2 GIS upgrade) ─────────────────────────────
// Maps each location's existing, real `category` + `sensorAvailable` fields to
// a device/event-axis `sensorType` used for marker styling on the new GIS map.
// This is a deterministic rule over real seed data — not invented per-row.
// Explicit `sensorType` on a LocationSeed always wins.
function deriveSensorType(loc: LocationSeed): SensorType {
  if (loc.sensorType) return loc.sensorType;
  if (!loc.sensorAvailable) return "environmental";

  switch (loc.category) {
    case "water":
      return "water";
    case "industrial":
      return "industrial";
    case "commercial":
      // Commercial zones with a deployed sensor are predominantly traffic-load
      // monitoring points in this dataset (CBD corridors, junctions, transit hubs).
      return "traffic";
    case "residential":
    case "park":
    case "landmark":
    default:
      return "environmental";
  }
}

// ─── Upsert helper ────────────────────────────────────────────────────────────
export async function seedMapData(): Promise<void> {
  console.log("[MapSeed] Starting map location seed …");

  for (const city of CITY_MAP_SEED) {
    // 1. Upsert CityMapConfig
    await CityMapConfig.findOneAndUpdate(
      { cityId: city.cityId },
      {
        cityId: city.cityId,
        center: city.center,
        zoom: city.zoom,
        bearing: city.bearing ?? 0,
        pitch: city.pitch ?? 0,
        waterBodies: city.waterBodies,
        zones: city.zones,
      },
      { upsert: true, new: true, setDefaultsOnInsert: true },
    );

    // 2. Upsert each MapLocation
    for (const loc of city.locations) {
      await MapLocation.findOneAndUpdate(
        { cityId: city.cityId, locationId: loc.locationId },
        {
          cityId: city.cityId,
          locationId: loc.locationId,
          name: loc.name,
          category: loc.category,
          latitude: loc.latitude,
          longitude: loc.longitude,
          mapX: loc.mapX,
          mapY: loc.mapY,
          pollutionMultiplier: loc.pollutionMultiplier,
          sensorAvailable: loc.sensorAvailable,
          sensorType: deriveSensorType(loc),
          description: loc.description,
        },
        { upsert: true, new: true, setDefaultsOnInsert: true },
      );
    }

    console.log(
      `[MapSeed]  ✓ ${city.cityId} — ${city.locations.length} locations, ${city.waterBodies.length} water bodies`,
    );
  }

  console.log(`[MapSeed] Done. ${CITY_MAP_SEED.length} cities seeded.`);
}

// ─── Standalone entry-point ───────────────────────────────────────────────────
if (require.main === module) {
  (async () => {
    const uri = process.env.MONGODB_URI || "mongodb://localhost:27017/greenguard";
    await mongoose.connect(uri);
    console.log("[MapSeed] Connected to MongoDB");
    await seedMapData();
    await mongoose.disconnect();
    console.log("[MapSeed] Disconnected. Exiting.");
    process.exit(0);
  })();
}
